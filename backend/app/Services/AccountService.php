                $key = "{$p}_{$c}";
                $value = $student->$key ?? '';
                $payload[$key] = in_array($c, ['tanggal_lahir'], true) && $value instanceof \DateTimeInterface
                    ? $value->toDateString()
                    : $value;
            }
        }

        return $payload;
    }
}
